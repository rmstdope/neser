#[cfg(test)]
mod tests {
    use super::DATA_ROM;
    use std::f64::consts::PI;

    /// The fullsnes formula for entry `index`, truncated towards zero.
    ///
    /// `tan(45°)` is the one entry where `f64` lands a hair under the exact value (`0.99999…`,
    /// truncating to `00FFFFh`); the true product is exactly `010000h`, so a relative nudge far
    /// below one LSB is added before truncating. It moves no other entry.
    fn formula(index: usize) -> u32 {
        let n = (index & 0xFF) as f64;
        let k = (index & 0x7F) as f64;
        let angle = k * PI / 256.0;
        let exact = match index {
            0x000..=0x0FF => {
                return if n == 0.0 {
                    0xFF_FFFF
                } else {
                    (0x80_0000 as f64 / n) as u32
                };
            }
            0x100..=0x1FF => 1_048_576.0 * n.sqrt(),
            0x200..=0x27F => 16_777_216.0 * angle.sin(),
            0x280..=0x2FF => 8_388_608.0 / 90.0 * (k / 128.0).asin().to_degrees(),
            0x300..=0x37F => 65_536.0 * angle.tan(),
            _ => 16_777_216.0 * angle.cos(),
        };
        ((exact * (1.0 + 1e-12)) as u32).min(0xFF_FFFF)
    }

    #[test]
    fn every_entry_matches_the_fullsnes_formula() {
        let mismatches: Vec<String> = (0..1024)
            .filter(|&i| DATA_ROM[i] != formula(i))
            .map(|i| format!("{i:03X}: {:06X} != {:06X}", DATA_ROM[i], formula(i)))
            .collect();
        assert!(
            mismatches.is_empty(),
            "{} mismatches: {mismatches:?}",
            mismatches.len()
        );
    }

    /// The first and last value fullsnes prints for each table.
    #[test]
    fn table_endpoints_match_fullsnes() {
        let endpoints = [
            (0x000, 0xFF_FFFF, 0x0FF, 0x00_8080), // Div
            (0x100, 0x00_0000, 0x1FF, 0xFF_7FDF), // Sqrt
            (0x200, 0x00_0000, 0x27F, 0xFF_FB10), // Sin
            (0x280, 0x00_0000, 0x2FF, 0x75_CEB4), // Asin
            (0x300, 0x00_0000, 0x37F, 0x51_7BB5), // Tan
            (0x380, 0xFF_FFFF, 0x3FF, 0x03_243A), // Cos
        ];
        for (first, first_value, last, last_value) in endpoints {
            assert_eq!(DATA_ROM[first], first_value, "entry {first:03X}");
            assert_eq!(DATA_ROM[last], last_value, "entry {last:03X}");
        }
    }
}
