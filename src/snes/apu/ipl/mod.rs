//! Embedded clean-room SNES APU IPL ROM.

pub const EMBEDDED_IPL: [u8; 64] = [
    // FFC0: mov x,EF
    0xCD, 0xEF, // FFC2: mov sp,x
    0xBD, // FFC3: mov a,00
    0xE8, 0x00, // FFC5: mov [x],a
    0xC6, // FFC6: dec x
    0x1D, // FFC7: jnz FFC5
    0xD0, 0xFC, // FFC9: mov [F4],AA
    0x8F, 0xAA, 0xF4, // FFCC: mov [F5],BB
    0x8F, 0xBB, 0xF5, // FFCF: cmp [F4],CC
    0x78, 0xCC, 0xF4, // FFD2: jnz FFCF
    0xD0, 0xFB, // FFD4: jr FFEF
    0x2F, 0x19, // FFD6: mov y,[F4]
    0xEB, 0xF4, // FFD8: jnz FFD6
    0xD0, 0xFC, // FFDA: cmp y,[F4]
    0x7E, 0xF4, // FFDC: jnz FFE9
    0xD0, 0x0B, // FFDE: mov a,[F5]
    0xE4, 0xF5, // FFE0: mov [F4],y
    0xCB, 0xF4, // FFE2: mov [[00]+y],a
    0xD7, 0x00, // FFE4: inc y
    0xFC, // FFE5: jnz FFDA
    0xD0, 0xF3, // FFE7: inc [01]
    0xAB, 0x01, // FFE9: jns FFDA
    0x10, 0xEF, // FFEB: cmp y,[F4]
    0x7E, 0xF4, // FFED: jns FFDA
    0x10, 0xEB, // FFEF: movw ya,[F6]
    0xBA, 0xF6, // FFF1: movw [00],ya
    0xDA, 0x00, // FFF3: movw ya,[F4]
    0xBA, 0xF4, // FFF5: mov [F4],a
    0xC4, 0xF4, // FFF7: mov a,y
    0xDD, // FFF8: mov x,a
    0x5D, // FFF9: jnz FFD6
    0xD0, 0xDB, // FFFB: jmp [0000+x]
    0x1F, 0x00, 0x00, // FFFE: dw FFC0 (reset vector)
    0xC0, 0xFF,
];

#[cfg(test)]
mod tests {
    #[test]
    fn embedded_ipl_matches_documented_boot_rom_bytes() {
        let expected: [u8; 64] = [
            0xCD, 0xEF, 0xBD, 0xE8, 0x00, 0xC6, 0x1D, 0xD0, 0xFC, 0x8F, 0xAA, 0xF4, 0x8F, 0xBB,
            0xF5, 0x78, 0xCC, 0xF4, 0xD0, 0xFB, 0x2F, 0x19, 0xEB, 0xF4, 0xD0, 0xFC, 0x7E, 0xF4,
            0xD0, 0x0B, 0xE4, 0xF5, 0xCB, 0xF4, 0xD7, 0x00, 0xFC, 0xD0, 0xF3, 0xAB, 0x01, 0x10,
            0xEF, 0x7E, 0xF4, 0x10, 0xEB, 0xBA, 0xF6, 0xDA, 0x00, 0xBA, 0xF4, 0xC4, 0xF4, 0xDD,
            0x5D, 0xD0, 0xDB, 0x1F, 0x00, 0x00, 0xC0, 0xFF,
        ];
        assert_eq!(super::EMBEDDED_IPL, expected);
    }
}
